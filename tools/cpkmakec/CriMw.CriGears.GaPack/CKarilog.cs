	public static void KariLog(TextWriter tw, Option opt)
	{
		tw.Write("こっから仮ログ\n");
		tw.Write("------ bootrom ver 2.01 -----\n");
		tw.Write("......boot!\n");
		tw.Write("eikou -> C:rahmen\\tsukemen\\bin\\Release\\ikemen.exe\n");
		tw.Write("\n");
		tw.Write("#CRIFS,H,{0:d},XXXXXX Ver.7.69 Build:Jun  4 2008 19:23:39\n", DateTime.Now.ToShortDateString());
		Random random = new Random();
		if (opt == Option.Yokuderu)
		{
			for (int i = 0; i < 50; i++)
			{
				int num = ((random.Next(2) != 0) ? random.Next(m_table.Length) : (100 + random.Next(10)));
				m_table[num].Karilog(tw, "Hanagumi", SF.Part.All);
			}
		}
		else if (opt == Option.Kantan20080806)
		{
			int num2 = 0;
			for (int j = 0; j < 3; j++)
			{
				for (int i = 0; i < 26; i++)
				{
					SF.KariWrite_Load(tw, "eigox3", "file" + i + ".dat", 0, 10000);
					if (random.Next(3) == 0)
					{
						SF.KariWrite_Load(tw, "eigox3", "bgm.adx", num2, 30000);
						num2 += 3000;
					}
				}
			}
		}
		else if (opt == Option.Part)
		{
			for (int i = 0; i < 50; i++)
			{
				m_table[i * 3].Karilog(tw, "Hanagumi", SF.Part.Mae);
			}
			for (int i = 0; i < 50; i++)
			{
				m_table[i * 3].Karilog(tw, "Hanagumi", SF.Part.Ato);
			}
		}
		else
		{
			if (opt != Option.Group)
			{
				while (true)
				{
					bool flag = true;
				}
			}
			for (int i = 0; i < 33; i++)
			{
				int num = random.Next(m_table.Length);
				if (random.Next(2) == 0)
				{
					m_table[num].Karilog(tw, "Hanagumi", SF.Part.All);
				}
				else
				{
					m_table[num].Karilog(tw, "Tsukigumi", SF.Part.All);
				}
			}
		}
		tw.Write("仮ログ終わり\n");
	}

	public static void KariLogFile(string filename, Option opt)
	{
		Stream stream = File.Open(filename, FileMode.Create);
		using StreamWriter streamWriter = new StreamWriter(stream);
		KariLog(streamWriter, opt);
		streamWriter.Close();
	}
